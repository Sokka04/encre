def _url_has_forbidden_params(url: str) -> str | None:
    parts = urlsplit(url)
    for key, val in parse_qsl(parts.query, keep_blank_values=True):
        k_low = key.lower()
        v_low = val.lower()
        if k_low.startswith("utm_") or k_low in TRACKING_QUERY_KEYS:
            return f"paramètre interdit '{key}'"
        for tok in AI_URL_TOKENS:
            if tok in k_low or tok in v_low:
                return f"marqueur IA '{tok}' dans la requête"
    if parts.fragment:
        frag_low = parts.fragment.lower()
        if "utm_" in frag_low:
            return "paramètre 'utm_' dans le fragment"
        for tok in AI_URL_TOKENS:
            if tok in frag_low:
                return f"marqueur IA '{tok}' dans le fragment"
    return None


def _detect_language(text: str, requested: str) -> str:
    if requested in {"fr", "en"}:
        return requested
    low = f" {text.lower()} "
    fr_score = sum(
        low.count(tok)
        for tok in (" le ", " la ", " les ", " des ", " dans ", " pour ", " une ")
    )
    fr_score += sum(low.count(ch) for ch in ("é", "è", "à", "ç", "’"))
    en_score = sum(
        low.count(tok)
        for tok in (" the ", " and ", " with ", " for ", " that ", " this ")
    )
    return "fr" if fr_score >= en_score else "en"


def _is_neutral_hex(hex_val: str) -> bool:
    v = hex_val.strip().lstrip("#").upper()
    if v in {"AUTO", ""}:
        return True
    if len(v) != 6 or not re.fullmatch(r"[0-9A-F]{6}", v):
        return True
    r, g, b = int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16)
    return max(r, g, b) - min(r, g, b) <= 25


def _split_sentences(text: str) -> list[str]:
    cleaned = URL_RE.sub("URL", text)
    cleaned = re.sub(
        r"\b(M|Mme|Mlle|Dr|Pr|art|al|fig|cf|etc|p|vol|n°)\.", r"\1", cleaned
    )
    cleaned = re.sub(r"(\d)\.(\d)", r"\1,\2", cleaned)
    raw = re.split(r"[.!?]+(?:\s+|$)", cleaned)
    return [s.strip() for s in raw if len(s.split()) >= 2]


def _extract_runs_from_p(
    p_elem: ET.Element,
    used_fonts: set[str],
    used_colors: set[str],
) -> tuple[list[tuple[str, bool]], str]:
    """Extrait les segments de texte et métadonnées police/couleur d'un paragraphe XML."""
    for shd in p_elem.iter(f"{W}shd"):
        fill = shd.attrib.get(f"{W}fill", "").upper()
        if fill:
            used_colors.add(fill)

    run_nodes: list[tuple[ET.Element, bool]] = []
    for sub in p_elem:
        if sub.tag == f"{W}r":
            run_nodes.append((sub, False))
        elif sub.tag.endswith("hyperlink"):
            for hsub in sub:
                if hsub.tag == f"{W}r":
                    run_nodes.append((hsub, True))

    runs_data: list[tuple[str, bool]] = []
    for rnode, is_link in run_nodes:
        rpr = rnode.find(f"{W}rPr")
        is_bold = False
        if rpr is not None:
            b_el = rpr.find(f"{W}b")
            if b_el is not None and b_el.attrib.get(f"{W}val", "1") not in {
                "0",
                "false",
            }:
                is_bold = True
            rf = rpr.find(f"{W}rFonts")
            if rf is not None:
                for attr in ("ascii", "hAnsi"):
                    val = rf.attrib.get(f"{W}{attr}")
                    if val:
                        used_fonts.add(val)
            col = rpr.find(f"{W}color")
            if col is not None and col.attrib.get(f"{W}val"):
                used_colors.add(col.attrib[f"{W}val"].upper())

        t_parts = [t.text for t in rnode.findall(f"{W}t") if t.text]
        rtext = "".join(t_parts)
        if rtext:
            runs_data.append((rtext, is_bold and not is_link))

    return runs_data, "".join(t for t, _ in runs_data)


def _extract_docx_data(path: Path) -> dict[str, Any]:
    with zipfile.ZipFile(path, "r") as zf:
        names = set(zf.namelist())
        styles_info: dict[str, dict[str, Any]] = {}
        style_names_by_id: dict[str, str] = {}

        if "word/styles.xml" in names:
            sroot = ET.fromstring(zf.read("word/styles.xml"))
            for st in sroot.findall(f"{W}style"):
                sid = st.attrib.get(f"{W}styleId", "")
                name_el = st.find(f"{W}name")
                sname = (
                    name_el.attrib.get(f"{W}val", "") if name_el is not None else sid
                )
                style_names_by_id[sid] = sname
                rpr = st.find(f"{W}rPr")
                ppr = st.find(f"{W}pPr")
                fonts: set[str] = set()
                colors: set[str] = set()
                if rpr is not None:
                    rf = rpr.find(f"{W}rFonts")
                    if rf is not None:
                        for attr in ("ascii", "hAnsi"):
                            val = rf.attrib.get(f"{W}{attr}")
                            if val:
                                fonts.add(val)
                    col = rpr.find(f"{W}color")
                    if col is not None and col.attrib.get(f"{W}val"):
                        colors.add(col.attrib[f"{W}val"].upper())
                keep_next = ppr is not None and ppr.find(f"{W}keepNext") is not None
                styles_info[sid] = {
                    "name": sname,
                    "fonts": fonts,
                    "colors": colors,
                    "keep_next": keep_next,
                }

        paragraphs: list[ParagraphItem] = []
        used_fonts: set[str] = set()
        used_colors: set[str] = set()
        used_style_ids: set[str] = {"Normal"}
        tables_meta: list[dict[str, Any]] = []
        has_toc = False
        has_title_pg = False
        has_page_break = False

        if "word/document.xml" in names:
            droot = ET.fromstring(zf.read("word/document.xml"))
            body = droot.find(f"{W}body")
            if body is not None:
                in_toc_field = False
                p_index = 0
                for child in body:
                    if child.tag == f"{W}p":
                        p_index += 1
                        ppr = child.find(f"{W}pPr")
                        sid = ""
                        if ppr is not None:
                            ps = ppr.find(f"{W}pStyle")
                            if ps is not None:
                                sid = ps.attrib.get(f"{W}val", "")
                                if sid:
                                    used_style_ids.add(sid)

                        sname_low = style_names_by_id.get(sid, sid).lower()
                        is_heading = bool(
                            re.match(r"^(?:heading|titre)\s*[1-6]$", sname_low)
                        )
                        is_list = (
                            ppr is not None and ppr.find(f"{W}numPr") is not None
                        ) or (
                            "list" in sname_low
                            or "bullet" in sname_low
                            or "puce" in sname_low
                        )
                        is_caption = "caption" in sname_low or "légende" in sname_low
                        p_keep_next = (
                            ppr is not None and ppr.find(f"{W}keepNext") is not None
                        ) or bool(styles_info.get(sid, {}).get("keep_next", False))

                        has_drawing_or_break = False
                        fld_instr_text = ""

                        for elem in child.iter():
                            if elem.tag in {
                                f"{W}drawing",
                                f"{W}pict",
                                f"{W}br",
                                f"{W}sectPr",
                            }:
                                has_drawing_or_break = True
                                if (
                                    elem.tag == f"{W}br"
                                    and elem.attrib.get(f"{W}type") == "page"
                                ):
                                    has_page_break = True
                            if elem.tag == f"{W}instrText" and elem.text:
                                fld_instr_text += elem.text
                                if "TOC" in elem.text:
                                    has_toc = True
                                    in_toc_field = True
                            if elem.tag == f"{W}fldChar":
                                ftype = elem.attrib.get(f"{W}fldCharType")
                                if ftype == "end" and in_toc_field:
                                    in_toc_field = False

                        runs_data, full_text = _extract_runs_from_p(
                            child, used_fonts, used_colors
                        )
                        is_empty_spacer = (
                            not full_text.strip()
                            and not has_drawing_or_break
                            and not fld_instr_text
                        )
                        paragraphs.append(
                            ParagraphItem(
                                text=full_text,
                                style_id=sid or "Normal",
                                is_heading=is_heading,
                                is_list=is_list,
                                is_caption=is_caption,
                                is_toc=in_toc_field or ("TOC" in fld_instr_text),
                                is_empty_spacer=is_empty_spacer,
                                keep_next=p_keep_next,
                                runs=runs_data,
                                location=f"Paragraphe {p_index}",
                            )
                        )

                    elif child.tag == f"{W}tbl":
                        tbl_idx = len(tables_meta) + 1
                        rows = child.findall(f"{W}tr")
                        row_count = len(rows)
                        has_tbl_header = False
                        all_cant_split = True
                        for r_idx, tr in enumerate(rows):
                            tr_pr = tr.find(f"{W}trPr")
                            if (
                                r_idx == 0
                                and tr_pr is not None
                                and tr_pr.find(f"{W}tblHeader") is not None
                            ):
                                has_tbl_header = True
                            if tr_pr is None or tr_pr.find(f"{W}cantSplit") is None:
                                all_cant_split = False
                            for shd in tr.iter(f"{W}shd"):
                                fill = shd.attrib.get(f"{W}fill", "").upper()
                                if fill:
                                    used_colors.add(fill)
                            for col in tr.iter(f"{W}color"):
                                val = col.attrib.get(f"{W}val", "").upper()
                                if val:
                                    used_colors.add(val)
                            for rf in tr.iter(f"{W}rFonts"):
                                for attr in ("ascii", "hAnsi"):
                                    val = rf.attrib.get(f"{W}{attr}")
                                    if val:
                                        used_fonts.add(val)
                            for c_idx, tc in enumerate(tr.findall(f"{W}tc"), start=1):
                                for p_el in tc.findall(f"{W}p"):
                                    ppr = p_el.find(f"{W}pPr")
                                    sid = ""
                                    if ppr is not None:
                                        ps = ppr.find(f"{W}pStyle")
                                        if ps is not None:
                                            sid = ps.attrib.get(f"{W}val", "")
                                            if sid:
                                                used_style_ids.add(sid)
                                    sname_low = style_names_by_id.get(sid, sid).lower()
                                    is_list = (
                                        ppr is not None
                                        and ppr.find(f"{W}numPr") is not None
                                    ) or (
                                        "list" in sname_low
                                        or "bullet" in sname_low
                                        or "puce" in sname_low
                                    )
                                    runs_data, full_text = _extract_runs_from_p(
                                        p_el, used_fonts, used_colors
                                    )
                                    if full_text.strip():
                                        paragraphs.append(
                                            ParagraphItem(
                                                text=full_text,
                                                style_id=sid or "TableCell",
                                                is_heading=False,
                                                is_list=is_list,
                                                is_caption=False,
                                                is_toc=False,
                                                is_empty_spacer=False,
                                                keep_next=False,
                                                is_table_cell=True,
                                                runs=runs_data,
                                                location=f"Tableau {tbl_idx}, L{r_idx + 1}C{c_idx}",
                                            )
                                        )
                        tables_meta.append(
                            {
                                "index": tbl_idx,
                                "rows": row_count,
                                "has_tbl_header": has_tbl_header,
                                "all_cant_split": all_cant_split,
                            }
                        )

                for sect_pr in body.iter(f"{W}sectPr"):
                    if sect_pr.find(f"{W}titlePg") is not None:
                        has_title_pg = True

        for sid in used_style_ids:
            info = styles_info.get(sid)
            if info:
                used_fonts.update(info["fonts"])
                used_colors.update(info["colors"])

        update_fields = False
        if "word/settings.xml" in names:
            set_root = ET.fromstring(zf.read("word/settings.xml"))
            uf = set_root.find(f"{W}updateFields")
            if uf is not None and uf.attrib.get(f"{W}val", "").lower() in {
                "true",
                "1",
                "on",
            }:
                update_fields = True

        metadata_blobs: list[tuple[str, str]] = []
        for meta_name in (
            "docProps/core.xml",
            "docProps/app.xml",
            "docProps/custom.xml",
        ):
            if meta_name in names:
                metadata_blobs.append(
                    (meta_name, zf.read(meta_name).decode("utf-8", errors="replace"))
                )

        rels_urls: list[tuple[str, str]] = []
        for name in sorted(names):
            if name.startswith("word/_rels/") and name.endswith(".rels"):
                rroot = ET.fromstring(zf.read(name))
                for rel in rroot:
                    if rel.attrib.get("TargetMode") == "External":
                        target = rel.attrib.get("Target", "")
                        if target:
                            rels_urls.append((name, target))

        extra_xml_texts: list[tuple[str, str]] = []
        for name in sorted(names):
            if name in {
                "word/footnotes.xml",
                "word/endnotes.xml",
                "word/comments.xml",
            } or (
                name.startswith(("word/header", "word/footer"))
                and name.endswith(".xml")
            ):
                xroot = ET.fromstring(zf.read(name))
                p_texts = []
                for p_el in xroot.iter(f"{W}p"):
                    pt = "".join(el.text or "" for el in p_el.iter(f"{W}t"))
                    if pt:
                        p_texts.append(pt)
                txt = (
                    "\n".join(p_texts)
                    if p_texts
                    else "".join(el.text or "" for el in xroot.iter(f"{W}t"))
                )
                if txt.strip():
                    extra_xml_texts.append((name, txt))
                if name == "word/comments.xml":
                    for comment_el in xroot.iter(f"{W}comment"):
                        c_author = comment_el.attrib.get(f"{W}author", "").strip()
                        c_initials = comment_el.attrib.get(f"{W}initials", "").strip()
                        if c_author:
                            metadata_blobs.append(
                                ("word/comments.xml", f"comment_author={c_author}")
                            )
                        if c_initials:
                            metadata_blobs.append(
                                ("word/comments.xml", f"comment_initials={c_initials}")
                            )

    return {
        "paragraphs": paragraphs,
        "used_fonts": sorted(used_fonts),
        "used_colors": sorted(used_colors),
        "tables": tables_meta,
        "has_toc": has_toc,
        "update_fields": update_fields,
        "has_title_pg": has_title_pg,
        "has_page_break": has_page_break,
        "has_headers_or_footers": any(
            n.startswith(("word/header", "word/footer")) for n in names
        ),
        "metadata_blobs": metadata_blobs,
        "rels_urls": rels_urls,
        "extra_xml_texts": extra_xml_texts,
    }


def _extract_text_doc_data(path: Path) -> list[ParagraphItem]:
    raw = path.read_text(encoding="utf-8", errors="replace")
    is_md = path.suffix.lower() in {".md", ".markdown"}
    lines = raw.splitlines()
    paragraphs: list[ParagraphItem] = []
    in_code_fence = False

    for idx, line in enumerate(lines, start=1):
        stripped = line.strip()
        if is_md and stripped.startswith("```"):
            in_code_fence = not in_code_fence
            continue
        if in_code_fence or not stripped:
            continue

        # Masque le code inline dans les fichiers Markdown pour éviter les faux positifs
        clean_line = re.sub(r"`[^`]+`", " ", line) if is_md else line

        is_heading = bool(is_md and re.match(r"^\s*#{1,6}\s+", line))
        is_list = bool(re.match(r"^\s*(?:[-*+]|\d+\.)\s+", line))

        text_val = (
            re.sub(r"^\s*#{1,6}\s+", "", clean_line) if is_heading else clean_line
        )
        if is_list:
            text_val = re.sub(r"^\s*(?:[-*+]|\d+\.)\s+", "", text_val)

        # Détecte le format "- **Terme** : ..." avant de retirer le Markdown
        bold_lead = bool(
            is_md
            and is_list
            and re.match(r"^\s*(?:[-*+]|\d+\.)\s+\*\*[^*]+\*\*\s*:", line)
        )
        runs = None
        if bold_lead:
            runs = [("BOLD_LEAD:", True)]
        else:
            text_val = (
                re.sub(r"\*\*([^*]+)\*\*", r"\1", text_val) if is_md else text_val
            )

        paragraphs.append(
            ParagraphItem(
                text=text_val.strip(),
                is_heading=is_heading,
                is_list=is_list,
                runs=runs,
                location=f"Ligne {idx}",
            )
        )
    return paragraphs


def audit_document(
    path: Path,
    *,
    lang: str = "auto",
) -> dict[str, Any]:
    """Exécute les 4 contrôles d'audit sur un fichier .docx, .md ou .txt."""
    target = Path(path).resolve()
    if not target.exists():
        raise FileNotFoundError(f"Fichier introuvable : {target}")

    is_docx = target.suffix.lower() == ".docx"
    findings: list[Finding] = []

    if is_docx:
        docx_data = _extract_docx_data(target)
        paragraphs: list[ParagraphItem] = docx_data["paragraphs"]
    else:
        docx_data = None
        paragraphs = _extract_text_doc_data(target)

    full_prose = "\n".join(p.text for p in paragraphs if p.text.strip())
    detected_lang = _detect_language(full_prose, lang)

    borderline_counts: dict[str, tuple[int, str]] = {}
    connector_flags: list[bool] = []
    body_sentences: list[str] = []
    consecutive_empty = 0

    for p in paragraphs:
        txt = p.text
        loc = p.location

        if is_docx:
            if p.is_empty_spacer:
                consecutive_empty += 1
                if consecutive_empty == 2:
                    findings.append(
                        Finding(
                            control=3,
                            severity="ALERTE",
                            code="empty_spacer_paragraphs",
                            message="Paragraphes vides consécutifs utilisés comme espacement.",
                            location=loc,
                        )
                    )
                continue
            consecutive_empty = 0

        if not txt.strip():
            continue

        # Vérifications sur tout texte (même TOC / légendes) pour les fuites critiques
        if is_docx and (
            RAW_MD_BOLD_RE.search(txt)
            or RAW_MD_HEADING_RE.match(txt)
            or RAW_MD_FENCE_RE.search(txt)
            or RAW_MD_HR_RE.match(txt)
        ):
            findings.append(
                Finding(
                    control=2,
                    severity="ERREUR",
                    code="raw_markdown",
                    message=f"Résidu Markdown détecté dans le .docx : « {txt[:70]} ».",
                    location=loc,
                )
            )

        if PLACEHOLDER_RE.search(txt):
            findings.append(
                Finding(
                    control=2,
                    severity="ERREUR",
                    code="placeholder_text",
                    message=f"Texte factice non remplacé : « {txt[:70]} ».",
                    location=loc,
                )
            )

        for match in URL_RE.finditer(txt):
            u, _ = split_trailing_punctuation(match.group(0))
            bad = _url_has_forbidden_params(u)
            if bad:
                findings.append(
                    Finding(
                        control=2,
                        severity="ERREUR",
                        code="dirty_url_text",
                        message=f"URL souillée ({bad}) : {u}",
                        location=loc,
                    )
                )

        txt_without_urls = URL_RE.sub(" ", txt)
        m_sig = AI_SIGNATURE_TEXT_RE.search(txt_without_urls)
        if m_sig:
            findings.append(
                Finding(
                    control=2,
                    severity="ERREUR",
                    code="ai_signature_text",
                    message=f"Signature ou trace d'IA détectée dans le texte : « {m_sig.group(0).strip()} ».",
                    location=loc,
                )
            )

        if p.is_toc:
            continue

        # Contrôle 1 : Style anti-IA
        if "\u2014" in txt:
            findings.append(
                Finding(
                    control=1,
                    severity="ERREUR",
                    code="em_dash",
                    message="Tiret cadratin « — » détecté en prose.",
                    location=loc,
                )
            )

        en_dash_incises = len(re.findall(r"(?<!\d)\s\u2013\s(?!\d)", txt))
        if en_dash_incises >= 2:
            findings.append(
                Finding(
                    control=1,
                    severity="ALERTE",
                    code="en_dash_incise",
                    message=f"{en_dash_incises} tirets demi-cadratins en incise dans un même bloc.",
                    location=loc,
                )
            )

        if EMOJI_RE.search(txt):
            findings.append(
                Finding(
                    control=1,
                    severity="ERREUR",
                    code="emoji",
                    message="Emoji détecté dans un document formel.",
                    location=loc,
                )
            )

        if p.is_list and p.runs:
            if not is_docx and p.runs[0][0] == "BOLD_LEAD:":
                findings.append(
                    Finding(
                        control=1,
                        severity="ERREUR",
                        code="bold_lead_bullet",
                        message=f"Puce au format « **Mot-clé** : ... » : « {txt[:65]} ».",
                        location=loc,
                    )
                )
            elif is_docx and len(p.runs) >= 2 and p.runs[0][1]:
                first_txt = p.runs[0][0].strip()
                second_txt = p.runs[1][0].lstrip()
                if first_txt.endswith(":") or second_txt.startswith(":"):
                    findings.append(
                        Finding(
                            control=1,
                            severity="ERREUR",
                            code="bold_lead_bullet",
                            message=f"Puce au format « **Mot-clé** : ... » : « {txt[:65]} ».",
                            location=loc,
                        )
                    )

        if (
            p.is_heading
            and ":" in txt
            and not HEADING_LABEL_PREFIX_RE.match(txt.strip())
        ):
            left, right = txt.split(":", 1)
            if len(left.split()) >= 2 and len(right.split()) >= 2:
                findings.append(
                    Finding(
                        control=1,
                        severity="ALERTE",
                        code="dramatic_colon_heading",
                        message=f"Titre en deux morceaux avec deux-points : « {txt} ».",
                        location=loc,
                    )
                )

        if is_docx and p.is_heading and not p.keep_next:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="heading_without_keep_next",
                    message=f"Titre sans keep_with_next (risque de titre orphelin) : « {txt} ».",
                    location=loc,
                )
            )

        for label, rx, code in (
            ("Fausse antithèse dramatique", ANTITHESIS_RE, "false_antithesis"),
            (
                "Méta-commentaire ou sur-justification",
                META_COMMENTARY_RE,
                "meta_commentary",
            ),
            (
                "Ouverture ou clôture générique IA",
                GENERIC_OPEN_CLOSE_RE,
                "generic_framing",
            ),
            ("Remplissage conversationnel", FILLER_RE, "conversational_filler"),
        ):
            m = rx.search(txt)
            if m:
                findings.append(
                    Finding(
                        control=1,
                        severity="ERREUR",
                        code=code,
                        message=f"{label} : « {m.group(0)} ».",
                        location=loc,
                    )
                )

        m_pure = PURE_SLOP_RE.search(txt)
        if m_pure:
            findings.append(
                Finding(
                    control=1,
                    severity="ERREUR",
                    code="ai_slop_lexicon",
                    message=f"Lexique IA à éliminer : « {m_pure.group(0)} ».",
                    location=loc,
                )
            )

        for m_b in BORDERLINE_SLOP_RE.finditer(txt):
            term = m_b.group(0).lower()
            prev_count, prev_loc = borderline_counts.get(term, (0, loc))
            borderline_counts[term] = (prev_count + 1, prev_loc)

        # Détection des mises en gras décoratives en milieu de paragraphe (.docx)
        if (
            is_docx
            and not p.is_heading
            and not p.is_list
            and not p.is_caption
            and not p.is_table_cell
            and p.runs
        ):
            word_count = len(txt.split())
            if word_count >= 12 and len(p.runs) >= 2:
                has_bold = any(b for _, b in p.runs)
                has_non_bold = any(not b for _, b in p.runs)
                starts_with_label = bool(p.runs[0][1] and ":" in p.runs[0][0][:40])
                if has_bold and has_non_bold and not starts_with_label:
                    findings.append(
                        Finding(
                            control=1,
                            severity="ALERTE",
                            code="decorative_bolding",
                            message="Gras dispersé en milieu de paragraphe.",
                            location=loc,
                        )
                    )

        is_body_prose = (
            not p.is_heading
            and not p.is_list
            and not p.is_caption
            and not p.is_table_cell
            and len(txt.split()) >= 6
        )
        if is_body_prose:
            has_conn = bool(CONNECTOR_START_RE.match(txt))
            connector_flags.append(has_conn)
            body_sentences.extend(_split_sentences(txt))

        # Contrôle 4 : Typographie française
        if detected_lang == "fr":
            text_no_urls = URL_RE.sub(" ", txt)
            m_apo = FR_CONTRACTION_APOSTROPHE_RE.search(text_no_urls)
            if m_apo:
                findings.append(
                    Finding(
                        control=4,
                        severity="ALERTE",
                        code="straight_apostrophe",
                        message=f"Apostrophe droite au lieu de « ’ » : « {m_apo.group(0)} ».",
                        location=loc,
                    )
                )
            m_quot = STRAIGHT_DOUBLE_QUOTE_RE.search(text_no_urls)
            if m_quot:
                findings.append(
                    Finding(
                        control=4,
                        severity="ALERTE",
                        code="straight_quotes",
                        message=f"Guillemets droits au lieu de « ... » : {m_quot.group(0)}.",
                        location=loc,
                    )
                )
            # Espace ordinaire ou absence d'espace devant ; ! ? ou : (hors heures 14:30)
            m_nbsp = re.search(
                r"(?:\S[ \t]+([;!?])|\S([!?])(?=\s|$)|"
                r"[A-Za-zÀ-ÖØ-öø-ÿ0-9»)][ \t]+:(?=\s|$)|"
                r"[A-Za-zÀ-ÖØ-öø-ÿ»)]:(?=\s|$))",
                text_no_urls,
            )
            if m_nbsp:
                findings.append(
                    Finding(
                        control=4,
                        severity="ALERTE",
                        code="missing_nbsp",
                        message="Espace insécable manquante devant ponctuation double (; : ! ?).",
                        location=loc,
                    )
                )
            m_cap = FR_UNACCENTED_CAP_RE.search(text_no_urls)
            if m_cap:
                findings.append(
                    Finding(
                        control=4,
                        severity="ALERTE",
                        code="unaccented_capital",
                        message=f"Majuscule non accentuée : « {m_cap.group(0).strip()} ».",
                        location=loc,
                    )
                )

    for term, (count, first_loc) in borderline_counts.items():
        if count >= 2:
            findings.append(
                Finding(
                    control=1,
                    severity="ERREUR",
                    code="repeated_ai_buzzword",
                    message=f"Terme IA répété {count} fois : « {term} ».",
                    location=first_loc,
                )
            )
        else:
            findings.append(
                Finding(
                    control=1,
                    severity="ALERTE",
                    code="borderline_ai_buzzword",
                    message=f"Terme souvent surutilisé par l'IA à vérifier : « {term} ».",
                    location=first_loc,
                )
            )

    consecutive_conn = any(
        connector_flags[i] and connector_flags[i + 1]
        for i in range(len(connector_flags) - 1)
    )
    if consecutive_conn:
        findings.append(
            Finding(
                control=1,
                severity="ERREUR",
                code="consecutive_connectors",
                message="Connecteurs scolaires empilés en début de paragraphes consécutifs.",
                location="Corps du texte",
            )
        )
    elif (
        len(connector_flags) >= 6
        and (sum(connector_flags) / len(connector_flags)) > 0.15
    ):
        findings.append(
            Finding(
                control=1,
                severity="ALERTE",
                code="high_connector_ratio",
                message="Proportion élevée de paragraphes démarrant par un connecteur scolaire (> 15 %).",
                location="Corps du texte",
            )
        )

    sentence_lengths = [len(s.split()) for s in body_sentences]
    avg_len = (
        (sum(sentence_lengths) / len(sentence_lengths)) if sentence_lengths else 0.0
    )
    std_len = 0.0
    if len(sentence_lengths) >= 8:
        variance = sum((n - avg_len) ** 2 for n in sentence_lengths) / len(
            sentence_lengths
        )
        std_len = math.sqrt(variance)
        if std_len < 4.5:
            findings.append(
                Finding(
                    control=1,
                    severity="ALERTE",
                    code="low_sentence_burstiness",
                    message=f"Rythme de phrases trop uniforme (écart-type : {std_len:.2f} mots).",
                    location="Corps du texte",
                )
            )

    # Contrôles spécifiques .docx (métadonnées, .rels, polices, couleurs, tableaux, nom de fichier)
    if is_docx and docx_data is not None:
        stem_low = target.stem.lower()
        if re.search(
            r"(?:^output$|^untitled$|^document_premier|^doc_generated|_v\d+|_final\b|_ai\b|_generated\b)",
            stem_low,
        ):
            findings.append(
                Finding(
                    control=3,
                    severity="ERREUR",
                    code="robotic_filename",
                    message=f"Nom de fichier générique ou technique : « {target.name} ».",
                    location=target.name,
                )
            )
        elif target.name.count("_") >= 3:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="underscore_filename",
                    message=f"Nom de fichier avec trop de tirets bas : « {target.name} ».",
                    location=target.name,
                )
            )

        for meta_name, blob in docx_data["metadata_blobs"]:
            blob_low = blob.lower()
            for marker in METADATA_LEAK_MARKERS:
                if marker in blob_low:
                    findings.append(
                        Finding(
                            control=2,
                            severity="ERREUR",
                            code="xml_metadata_leak",
                            message=f"Empreinte technique/IA « {marker} » dans {meta_name}.",
                            location=meta_name,
                        )
                    )

        for rels_name, url in docx_data["rels_urls"]:
            bad = _url_has_forbidden_params(url)
            if bad:
                findings.append(
                    Finding(
                        control=2,
                        severity="ERREUR",
                        code="dirty_url_rels",
                        message=f"Lien externe souillé ({bad}) : {url}",
                        location=rels_name,
                    )
                )

        for part_name, part_txt in docx_data["extra_xml_texts"]:
            for match in URL_RE.finditer(part_txt):
                u, _ = split_trailing_punctuation(match.group(0))
                bad = _url_has_forbidden_params(u)
                if bad:
                    findings.append(
                        Finding(
                            control=2,
                            severity="ERREUR",
                            code="dirty_url_extra",
                            message=f"URL souillée ({bad}) : {u}",
                            location=part_name,
                        )
                    )
            if PLACEHOLDER_RE.search(part_txt):
                findings.append(
                    Finding(
                        control=2,
                        severity="ERREUR",
                        code="placeholder_extra",
                        message="Texte factice détecté dans en-tête, pied de page ou note.",
                        location=part_name,
                    )
                )
            part_no_urls = URL_RE.sub(" ", part_txt)
            m_sig_extra = AI_SIGNATURE_TEXT_RE.search(part_no_urls)
            if m_sig_extra:
                findings.append(
                    Finding(
                        control=2,
                        severity="ERREUR",
                        code="ai_signature_extra",
                        message=f"Signature ou trace d'IA détectée : « {m_sig_extra.group(0).strip()} ».",
                        location=part_name,
                    )
                )

        used_fonts = docx_data["used_fonts"]
        non_native = [f for f in used_fonts if f not in NATIVE_FONTS]
        if non_native:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="non_native_font",
                    message=f"Police(s) non native(s) détectée(s) : {', '.join(non_native)}.",
                    location="Polices",
                )
            )
        if len(used_fonts) > 1:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="multiple_fonts",
                    message=f"Plusieurs familles de polices détectées : {', '.join(used_fonts)}.",
                    location="Polices",
                )
            )

        non_neutral_colors: set[str] = set()
        for col in docx_data["used_colors"]:
            if col in FORBIDDEN_AI_COLORS:
                findings.append(
                    Finding(
                        control=3,
                        severity="ERREUR",
                        code="forbidden_ai_color",
                        message=f"Couleur IA interdite détectée : #{col}.",
                        location="Couleurs",
                    )
                )
            if not _is_neutral_hex(col):
                non_neutral_colors.add(col)
        if len(non_neutral_colors) > 2:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="too_many_colors",
                    message=f"Trop de couleurs chromatiques ({len(non_neutral_colors)}) : {', '.join(sorted(non_neutral_colors))}.",
                    location="Couleurs",
                )
            )

        for tbl in docx_data["tables"]:
            if tbl["rows"] >= 2:
                if not tbl["has_tbl_header"]:
                    findings.append(
                        Finding(
                            control=3,
                            severity="ALERTE",
                            code="table_missing_header_repeat",
                            message=f"Tableau {tbl['index']} sans répétition d'en-tête (w:tblHeader).",
                            location=f"Tableau {tbl['index']}",
                        )
                    )
                if not tbl["all_cant_split"]:
                    findings.append(
                        Finding(
                            control=3,
                            severity="ALERTE",
                            code="table_missing_cant_split",
                            message=f"Tableau {tbl['index']} sans w:cantSplit sur toutes les lignes.",
                            location=f"Tableau {tbl['index']}",
                        )
                    )

        if docx_data["has_toc"] and not docx_data["update_fields"]:
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="toc_missing_update_fields",
                    message="Table des matières sans w:updateFields dans settings.xml.",
                    location="word/settings.xml",
                )
            )

        if (
            docx_data["has_page_break"]
            and docx_data["has_headers_or_footers"]
            and not docx_data["has_title_pg"]
        ):
            findings.append(
                Finding(
                    control=3,
                    severity="ALERTE",
                    code="missing_different_first_page",
                    message="En-tête/pied de page présent sans w:titlePg (page de garde non masquée).",
                    location="Sections",
                )
            )

    errors = [f for f in findings if f.severity == "ERREUR"]
    alerts = [f for f in findings if f.severity == "ALERTE"]
    return {
        "file": str(target),
        "language": detected_lang,
        "metrics": {
            "words": len(full_prose.split()),
            "body_sentences": len(sentence_lengths),
            "avg_sentence_words": round(avg_len, 2),
            "sentence_std_words": round(std_len, 2),
            "errors": len(errors),
            "alerts": len(alerts),
        },
        "findings": [asdict(f) for f in findings],
        "passed_default": len(errors) == 0,
        "passed_strict": len(errors) == 0 and len(alerts) == 0,
    }


def _print_report(report: dict[str, Any], strict: bool) -> None:
    m = report["metrics"]
    verdict = (
        "VALIDE"
        if (report["passed_strict"] if strict else report["passed_default"])
        else "REFUSÉ"
    )
    print(f"Audit Encre : {report['file']}")
    print(
        f"Langue : {report['language']} | Mots : {m['words']} | "
        f"Phrases analysées : {m['body_sentences']} "
        f"(moy. {m['avg_sentence_words']} mots, écart-type {m['sentence_std_words']})"
    )
    print(f"Résultat : {m['errors']} ERREUR(S), {m['alerts']} ALERTE(S) -> {verdict}")

    control_names = {
        1: "Contrôle 1 — Style anti-IA",
        2: "Contrôle 2 — Sources, URLs, Markdown et métadonnées",
        3: "Contrôle 3 — Technique et mise en page .docx",
        4: "Contrôle 4 — Typographie et langue",
    }
    findings = report["findings"]
    for cid in (1, 2, 3, 4):
        items = [f for f in findings if f["control"] == cid]
        if not items:
            continue
        print(f"\n[{control_names[cid]}]")
        for item in items:
            loc = f" ({item['location']})" if item["location"] else ""
            print(f"  - {item['severity']} [{item['code']}]{loc} : {item['message']}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Audite un document (.docx, .md, .txt) selon la phase 5 du protocole Encre."
    )
    parser.add_argument("path", type=Path, help="Chemin du fichier à auditer.")
    parser.add_argument(
        "--lang", choices=("auto", "fr", "en"), default="auto", help="Langue d'audit."
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Retourne le code 1 dès qu'une ALERTE est présente.",
    )
    parser.add_argument("--json", action="store_true", help="Sortie JSON structurée.")
    args = parser.parse_args(argv)

    report = audit_document(args.path, lang=args.lang)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        _print_report(report, strict=args.strict)

    ok = report["passed_strict"] if args.strict else report["passed_default"]
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())

AI_TOOL_MARKERS = (
    "python-docx",
    "python_docx",
    "pandoc",
    "libreoffice",
    "chatgpt",
    "openai",
    "claudecode",
    "claude",
    "anthropic",
    "gemini",
    "antigravity",
    "perplexity",
    "copilot",
    "generated by",
)

AI_URL_TOKENS = (
    "chatgpt",
    "openai",
    "claudecode",
    "claude",
    "anthropic",
    "gemini",
    "perplexity",
    "copilot",
    "bing",
)

TRACKING_QUERY_KEYS = {
    "utm_source",
    "utm_medium",
    "utm_campaign",
    "utm_term",
    "utm_content",
    "utm_id",
    "utm_name",
    "utm_reader",
    "utm_viz_id",
    "utm_pubreferrer",
    "utm_swu",
    "fbclid",
    "gclid",
    "gbraid",
    "wbraid",
    "mc_cid",
    "mc_eid",
    "yclid",
    "msclkid",
    "igshid",
    "ref",
}

CORE_NS = {
    "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties",
    "dc": "http://purl.org/dc/elements/1.1/",
    "dcterms": "http://purl.org/dc/terms/",
    "dcmitype": "http://purl.org/dc/dcmitype/",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
}
APP_NS = "http://schemas.openxmlformats.org/officeDocument/2006/extended-properties"
VT_NS = "http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"
CUSTOM_NS = "http://schemas.openxmlformats.org/officeDocument/2006/custom-properties"

URL_RE = re.compile(r"https?://[^\s<>\"']+")
REL_TAG_RE = re.compile(r"<Relationship\b[^>]*?/?>")
TARGET_ATTR_RE = re.compile(r'Target="([^"]*)"')
EXTERNAL_MODE_RE = re.compile(r'TargetMode="External"')
COMMENT_TAG_RE = re.compile(r"<w:comment\b[^>]*>")
COMMENT_AUTHOR_ATTR_RE = re.compile(r'w:author="([^"]*)"')
COMMENT_INITIALS_ATTR_RE = re.compile(r'w:initials="([^"]*)"')
FORBIDDEN_FILENAME_CHARS_RE = re.compile(r'[\\/:*?"<>|]+')


def contains_tool_or_ai_marker(value: str | None) -> bool:
    """Retourne True si une valeur de métadonnée révèle un outil ou une IA."""
    if not value:
        return False
    lowered = value.strip().lower()
    if any(marker in lowered for marker in AI_TOOL_MARKERS):
        return True
    return bool(re.search(r"\b(ai|ia)\b", lowered))


def clean_url(url: str) -> tuple[str, bool]:
    """Supprime les paramètres de tracking et marqueurs IA d'une URL."""
    if not url or not url.startswith(("http://", "https://")):
        return url, False

    parts = urlsplit(url)
    changed = False

    if parts.query:
        kept_params: list[tuple[str, str]] = []
        raw_pairs = parse_qsl(parts.query, keep_blank_values=True)
        for key, val in raw_pairs:
            k_low = key.lower()
            v_low = val.lower()
            is_tracking_key = k_low.startswith("utm_") or k_low in TRACKING_QUERY_KEYS
            has_ai_token = any(tok in k_low or tok in v_low for tok in AI_URL_TOKENS)
            if is_tracking_key or has_ai_token:
                changed = True
                continue
            kept_params.append((key, val))
        new_query = urlencode(kept_params, doseq=True)
    else:
        new_query = ""

    new_fragment = parts.fragment
    if new_fragment:
        frag_low = new_fragment.lower()
        if "utm_" in frag_low or any(tok in frag_low for tok in AI_URL_TOKENS):
            new_fragment = ""
            changed = True

    rebuilt = urlunsplit(
        (parts.scheme, parts.netloc, parts.path, new_query, new_fragment)
    )
    if rebuilt != url:
        changed = True
    return rebuilt, changed


def split_trailing_punctuation(raw_url: str) -> tuple[str, str]:
    """Détache la ponctuation finale d'une URL extraite d'un texte."""
    trailing = ""
    url = raw_url
    while url:
        last = url[-1]
        if (
            last in ".,;:!?"
            or (last == ")" and url.count(")") > url.count("("))
            or (last == "]" and url.count("]") > url.count("["))
        ):
            trailing = last + trailing
            url = url[:-1]
        else:
            break
    return url, trailing


def clean_urls_in_text(text: str) -> tuple[str, int]:
    """Nettoie toutes les URLs présentes dans une chaîne de texte brut."""
    count = 0

    def _replace(match: re.Match[str]) -> str:
        nonlocal count
        core, suffix = split_trailing_punctuation(match.group(0))
        cleaned, changed = clean_url(core)
        if changed:
            count += 1
        return f"{cleaned}{suffix}"

    return URL_RE.sub(_replace, text), count


def _clean_urls_in_xml_bytes(raw_bytes: bytes) -> tuple[bytes, int]:
    """Remplace uniquement les URLs dans un flux XML sans ré-sérialiser l'arbre."""
    text = raw_bytes.decode("utf-8")
    count = 0

    def _replace(match: re.Match[str]) -> str:
        nonlocal count
        raw_match = match.group(0)
        unescaped = html.unescape(raw_match)
        core, suffix = split_trailing_punctuation(unescaped)
        cleaned, changed = clean_url(core)
        if not changed:
            return raw_match
        count += 1
        restored = f"{cleaned}{suffix}"
        return restored.replace("&", "&amp;")

    updated = URL_RE.sub(_replace, text)
    return updated.encode("utf-8"), count


def _clean_rels_bytes(raw_bytes: bytes) -> tuple[bytes, int]:
    """Nettoie les attributs Target des liens externes dans un fichier .rels."""
    text = raw_bytes.decode("utf-8")
    count = 0

    def _replace_rel(match: re.Match[str]) -> str:
        nonlocal count
        tag = match.group(0)
        if not EXTERNAL_MODE_RE.search(tag):
            return tag

        def _replace_target(target_match: re.Match[str]) -> str:
            nonlocal count
            raw_target = html.unescape(target_match.group(1))
            cleaned, changed = clean_url(raw_target)
            if not changed:
                return target_match.group(0)
            count += 1
            escaped = html.escape(cleaned, quote=True)
            return f'Target="{escaped}"'

        return TARGET_ATTR_RE.sub(_replace_target, tag, count=1)

    updated = REL_TAG_RE.sub(_replace_rel, text)
    return updated.encode("utf-8"), count


def _sanitize_core_xml(
    raw_bytes: bytes,
    *,
    author: str | None,
    title: str | None,
) -> tuple[bytes, list[str]]:
    """Nettoie docProps/core.xml en conservant les espaces de noms OOXML."""
    for prefix, uri in CORE_NS.items():
        ET.register_namespace(prefix, uri)

    root = ET.fromstring(raw_bytes)
    changes: list[str] = []

    def _find_or_create(ns_key: str, tag_name: str) -> ET.Element:
        qname = f"{{{CORE_NS[ns_key]}}}{tag_name}"
        elem = root.find(qname)
        if elem is None:
            elem = ET.SubElement(root, qname)
        return elem

    for ns_key, tag_name in (("dc", "creator"), ("cp", "lastModifiedBy")):
        qname = f"{{{CORE_NS[ns_key]}}}{tag_name}"
        elem = root.find(qname)
        current = (elem.text or "") if elem is not None else ""
        if author is not None:
            if elem is None:
                elem = _find_or_create(ns_key, tag_name)
            if current != author:
                elem.text = author
                changes.append(f"core:{tag_name}")
        elif elem is not None and contains_tool_or_ai_marker(current):
            elem.text = ""
            changes.append(f"core:{tag_name}")

    if title is not None:
        title_elem = _find_or_create("dc", "title")
        if (title_elem.text or "") != title:
            title_elem.text = title
            changes.append("core:title")

    for ns_key, tag_name in (
        ("dc", "description"),
        ("dc", "subject"),
        ("cp", "keywords"),
    ):
        qname = f"{{{CORE_NS[ns_key]}}}{tag_name}"
        elem = root.find(qname)
        if elem is not None and contains_tool_or_ai_marker(elem.text):
            elem.text = ""
            changes.append(f"core:{tag_name}")

    payload = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    return payload, changes


def _sanitize_app_xml(raw_bytes: bytes) -> tuple[bytes, list[str]]:
    """Remplace le nom d'application générateur dans docProps/app.xml."""
    ET.register_namespace("", APP_NS)
    ET.register_namespace("vt", VT_NS)

    root = ET.fromstring(raw_bytes)
    changes: list[str] = []

    app_qname = f"{{{APP_NS}}}Application"
    app_elem = root.find(app_qname)
    if app_elem is None:
        app_elem = ET.SubElement(root, app_qname)
    if (app_elem.text or "") != "Microsoft Office Word":
        app_elem.text = "Microsoft Office Word"
        changes.append("app:Application")

    for tag_name in ("Company", "Manager"):
        elem = root.find(f"{{{APP_NS}}}{tag_name}")
        if elem is not None and contains_tool_or_ai_marker(elem.text):
            elem.text = ""
            changes.append(f"app:{tag_name}")

    payload = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    return payload, changes


def _sanitize_custom_xml(raw_bytes: bytes) -> tuple[bytes, list[str]]:
    """Supprime les propriétés personnalisées trahissant une IA ou un outil."""
    ET.register_namespace("", CUSTOM_NS)
    ET.register_namespace("vt", VT_NS)

    root = ET.fromstring(raw_bytes)
    changes: list[str] = []
    for prop in list(root):
        name = prop.attrib.get("name", "")
        text_content = "".join(prop.itertext())
        if contains_tool_or_ai_marker(name) or contains_tool_or_ai_marker(text_content):
            root.remove(prop)
            changes.append(f"custom:{name or 'property'}")

    payload = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    return payload, changes


def _sanitize_comments_xml(
    raw_bytes: bytes,
    *,
    author: str | None,
) -> tuple[bytes, int, list[str]]:
    """Nettoie les URLs et les auteurs trahissant une IA dans word/comments.xml."""
    cleaned_bytes, url_count = _clean_urls_in_xml_bytes(raw_bytes)
    text = cleaned_bytes.decode("utf-8")
    changes: list[str] = []

    def _patch_comment_tag(match: re.Match[str]) -> str:
        tag = match.group(0)
        m_auth = COMMENT_AUTHOR_ATTR_RE.search(tag)
        if not m_auth:
            return tag
        current_author = html.unescape(m_auth.group(1))
        if not contains_tool_or_ai_marker(current_author):
            return tag

        target_author = author or ""
        escaped_author = html.escape(target_author, quote=True)
        updated_tag = COMMENT_AUTHOR_ATTR_RE.sub(
            lambda _: f'w:author="{escaped_author}"',
            tag,
            count=1,
        )
        if COMMENT_INITIALS_ATTR_RE.search(updated_tag):
            initials = "".join(p[0].upper() for p in target_author.split() if p)[:3]
            escaped_initials = html.escape(initials, quote=True)
            updated_tag = COMMENT_INITIALS_ATTR_RE.sub(
                lambda _: f'w:initials="{escaped_initials}"',
                updated_tag,
                count=1,
            )
        if "comments:author" not in changes:
            changes.append("comments:author")
        return updated_tag

    updated_text = COMMENT_TAG_RE.sub(_patch_comment_tag, text)
    return updated_text.encode("utf-8"), url_count, changes


def sanitize_filename(name: str) -> str:
    """Nettoie un nom de fichier en supprimant les caractères interdits."""
    cleaned = FORBIDDEN_FILENAME_CHARS_RE.sub(" ", name)
    cleaned = re.sub(r"\s+", " ", cleaned).strip(" ._-")
    return cleaned or "Document"


def _is_target_word_xml(arcname: str) -> bool:
    if arcname in {"word/document.xml", "word/footnotes.xml", "word/endnotes.xml"}:
        return True
    return arcname.startswith(("word/header", "word/footer")) and arcname.endswith(
        ".xml"
    )


def sanitize_docx(
    input_path: Path,
    output_path: Path | None = None,
    *,
    author: str | None = None,
    title: str | None = None,
    in_place: bool = False,
) -> dict:
    """Nettoie les métadonnées XML et toutes les URLs d'un fichier .docx."""
    src = Path(input_path).resolve()
    if not src.exists():
        raise FileNotFoundError(f"Fichier introuvable : {src}")

    if in_place:
        dest = src
    elif output_path is not None:
        dest = Path(output_path).resolve()
    else:
        dest = src.with_name(f"{src.stem} - nettoye{src.suffix}")

    dest.parent.mkdir(parents=True, exist_ok=True)

    metadata_changes: list[str] = []
    urls_cleaned_rels = 0
    urls_cleaned_xml = 0

    fd, tmp_name = tempfile.mkstemp(
        prefix=".encre_", suffix=".docx", dir=str(dest.parent)
    )
    os.close(fd)
    tmp_path = Path(tmp_name)

    try:
        with zipfile.ZipFile(src, "r") as zin, zipfile.ZipFile(tmp_path, "w") as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)
                name = item.filename

                if name == "docProps/core.xml":
                    data, ch = _sanitize_core_xml(data, author=author, title=title)
                    metadata_changes.extend(ch)
                elif name == "docProps/app.xml":
                    data, ch = _sanitize_app_xml(data)
                    metadata_changes.extend(ch)
                elif name == "docProps/custom.xml":
                    data, ch = _sanitize_custom_xml(data)
                    metadata_changes.extend(ch)
                elif name == "word/comments.xml":
                    data, count, ch = _sanitize_comments_xml(data, author=author)
                    urls_cleaned_xml += count
                    metadata_changes.extend(ch)
                elif name.startswith("word/_rels/") and name.endswith(".rels"):
                    data, count = _clean_rels_bytes(data)
                    urls_cleaned_rels += count
                elif _is_target_word_xml(name):
                    data, count = _clean_urls_in_xml_bytes(data)
                    urls_cleaned_xml += count

                new_info = zipfile.ZipInfo(
                    filename=item.filename, date_time=item.date_time
                )
                new_info.compress_type = item.compress_type
                new_info.external_attr = item.external_attr
                zout.writestr(new_info, data)

        os.replace(tmp_path, dest)
    except Exception:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)
        raise

    return {
        "input": str(src),
        "output": str(dest),
        "metadata_changes": metadata_changes,
        "urls_cleaned_rels": urls_cleaned_rels,
        "urls_cleaned_xml": urls_cleaned_xml,
        "total_urls_cleaned": urls_cleaned_rels + urls_cleaned_xml,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Purge les métadonnées XML et paramètres de tracking IA d'un fichier .docx."
    )
    parser.add_argument("input_docx", type=Path, help="Chemin du fichier .docx source.")
    parser.add_argument(
        "-o", "--output", type=Path, default=None, help="Fichier .docx de sortie."
    )
    parser.add_argument(
        "--in-place", action="store_true", help="Écrase le fichier source."
    )
    parser.add_argument(
        "--author", type=str, default=None, help="Nom réel de l'auteur."
    )
    parser.add_argument(
        "--title", type=str, default=None, help="Titre exact du document."
    )
    parser.add_argument(
        "--json", action="store_true", help="Sortie structurée en JSON."
    )
    args = parser.parse_args(argv)

    if args.in_place and args.output is not None:
        parser.error("Utilisez soit --in-place soit --output, pas les deux.")

    result = sanitize_docx(
        args.input_docx,
        output_path=args.output,
        author=args.author,
        title=args.title,
        in_place=args.in_place,
    )

    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(f"Fichier nettoyé : {result['output']}")
        print(
            f"Métadonnées modifiées : {len(result['metadata_changes'])} "
            f"({', '.join(result['metadata_changes']) or 'aucune'})"
        )
        print(
            f"URLs nettoyées : {result['total_urls_cleaned']} "
            f"(relations : {result['urls_cleaned_rels']}, texte XML : {result['urls_cleaned_xml']})"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
